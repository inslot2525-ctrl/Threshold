// Local JSON-file persistence. Small on purpose: one household, a few thousand events.

import fs from 'node:fs'
import path from 'node:path'
import type { Device, HomeEvent, Incident, Settings } from '@/lib/types'

export interface State {
  settings: Settings
  incidents: Incident[]
  events: HomeEvent[]
  processedRequestIds: string[]
  devices: Device[]
}

const DATA_DIR = path.join(process.cwd(), 'data')
const STATE_FILE = path.join(DATA_DIR, 'state.json')
export const SNAPSHOT_DIR = path.join(DATA_DIR, 'snapshots')

const MAX_EVENTS = 2000
const MAX_INCIDENTS = 500
const MAX_REQUEST_IDS = 5000

export function defaultSettings(): Settings {
  return {
    personName: 'Person',
    caregiverName: 'Caregiver',
    timezone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    armMode: 'schedule',
    windowStart: '22:00',
    windowEnd: '06:00',
    corroborationSeconds: 90,
    returnGraceSeconds: 600,
    acceptGenericMotion: true,
    usePhoneCamera: true,
    doorSensorId: null,
    outdoorCameraId: null,
  }
}

export function loadState(): State {
  try {
    const raw = JSON.parse(fs.readFileSync(STATE_FILE, 'utf8'))
    return {
      settings: { ...defaultSettings(), ...raw.settings },
      incidents: raw.incidents ?? [],
      events: raw.events ?? [],
      processedRequestIds: raw.processedRequestIds ?? [],
      devices: raw.devices ?? [],
    }
  } catch {
    return {
      settings: defaultSettings(),
      incidents: [],
      events: [],
      processedRequestIds: [],
      devices: [],
    }
  }
}

export function saveState(state: State) {
  state.events = state.events.slice(0, MAX_EVENTS)
  state.incidents = state.incidents.slice(0, MAX_INCIDENTS)
  state.processedRequestIds = state.processedRequestIds.slice(-MAX_REQUEST_IDS)

  fs.mkdirSync(DATA_DIR, { recursive: true })
  const tmp = `${STATE_FILE}.tmp`
  fs.writeFileSync(tmp, JSON.stringify(state, null, 2))
  fs.renameSync(tmp, STATE_FILE)
}

export function writeSnapshot(incidentId: string, image: Buffer, ext: 'jpg' | 'png'): string {
  fs.mkdirSync(SNAPSHOT_DIR, { recursive: true })
  const file = `${incidentId}.${ext}`
  fs.writeFileSync(path.join(SNAPSHOT_DIR, file), image)
  return file
}

export function readSnapshot(file: string): Buffer | null {
  // file names are generated by us, but never trust a path from state blindly
  const safe = path.basename(file)
  try {
    return fs.readFileSync(path.join(SNAPSHOT_DIR, safe))
  } catch {
    return null
  }
}
